import sys

sys.dont_write_bytecode = True

from pathlib import Path
from pypdf import PdfReader

BASE_DIR = Path(__file__).resolve().parent
TWIN_DIR = BASE_DIR / "twin"


def _resolve_asset_path(filename: str) -> Path:
    """Resolves a knowledge base asset directly from the `twin/` directory."""
    asset_path = TWIN_DIR / filename
    if not asset_path.exists():
        raise FileNotFoundError(
            f"Missing required knowledge base asset '{filename}' in {TWIN_DIR}."
        )
    return asset_path


def load_linkedin_context(pdf_path: Path | None = None) -> str:
    """Extracts and formats multi-page text from `twin/linkedin.pdf`."""
    target_path = pdf_path or _resolve_asset_path("linkedin.pdf")
    reader = PdfReader(str(target_path))
    pages: list[str] = []
    for idx, page in enumerate(reader.pages, start=1):
        extracted = page.extract_text()
        if extracted:
            pages.append(f"--- LinkedIn Page {idx} ---\n{extracted.strip()}")
    return "\n\n".join(pages)


def load_text_context(filename: str) -> str:
    """Reads a UTF-8 text or markdown knowledge asset from `twin/`."""
    target_path = _resolve_asset_path(filename)
    return target_path.read_text(encoding="utf-8").strip()


